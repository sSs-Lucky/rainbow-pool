import {
  TABLE_W, TABLE_H, CUSHION, BALL_R, BALL_COLORS, PHYSICAL_R as R, BALL_MASS as M,
  PIXELS_PER_METRE as SCALE, GRAVITY as G, SLIDING_FRICTION as MU_S,
  ROLLING_FRICTION as MU_R, SPIN_DECELERATION, WALL_RESTITUTION,
  CUSHION_FRICTION, CUSHION_NOSE_HEIGHT, BALL_RESTITUTION, MAX_SHOT_SPEED, MAX_TIP_OFFSET,
} from './config.js';
import { POCKETS, CUSHION_SEGMENTS, closestOnSegment, pocketAt, validPlacement } from './geometry.js';

const I = 2 / 5 * M * R * R;
const EPS = 1e-9;
export const pocketPositions = () => POCKETS;
const make = (x, y, n) => ({ x, y, vx: 0, vy: 0, wx: 0, wy: 0, wz: 0, number: n, color: BALL_COLORS[n], potted: false });
export function rack() {
  const balls = [make(CUSHION + TABLE_W * .25, CUSHION + TABLE_H / 2, 0)];
  const order = [1, 9, 2, 10, 8, 3, 4, 11, 5, 12, 6, 13, 7, 14, 15];
  let n = 0;
  for (let row = 0; row < 5; row++) for (let i = 0; i <= row; i++) {
    balls.push(make(CUSHION + TABLE_W * .72 + row * (R * SCALE * Math.sqrt(3) + .1),
      CUSHION + TABLE_H / 2 + (i - row / 2) * (2 * BALL_R + .1), order[n++]));
  }
  return balls;
}
export function clampTip(tip = {}) {
  let x = Number.isFinite(tip?.x) ? tip.x : 0, y = Number.isFinite(tip?.y) ? tip.y : 0;
  const length = Math.hypot(x, y);
  if (length > MAX_TIP_OFFSET) { x *= MAX_TIP_OFFSET / length; y *= MAX_TIP_OFFSET / length; }
  return { x, y };
}
export function clearMotion(b) { b.vx = b.vy = b.wx = b.wy = b.wz = 0; }
export function shoot(cue, dirX, dirY, power, tip = {}) {
  const len = Math.hypot(dirX, dirY);
  if (!Number.isFinite(len) || len < EPS || !Number.isFinite(power)) return;
  const d = [dirX / len, -dirY / len], p = clampTip(tip);
  // Fixed delivered energy: angular momentum is generated by r × J, I=2mR²/5.
  const speed = Math.max(0, Math.min(1, power)) * MAX_SHOT_SPEED / Math.sqrt(1 + 2.5 * (p.x * p.x + p.y * p.y));
  cue.vx = speed * d[0]; cue.vy = speed * d[1];
  cue.wx = -2.5 * p.y * speed / R * d[1]; cue.wy = 2.5 * p.y * speed / R * d[0];
  cue.wz = 2.5 * p.x * speed / R;
}
export function energy(b) {
  return .5 * M * (b.vx * b.vx + b.vy * b.vy) + .5 * I * ((b.wx || 0) ** 2 + (b.wy || 0) ** 2 + (b.wz || 0) ** 2);
}
export function allStopped(balls) {
  // Axial spin alone cannot translate a ball on a level cloth and need not delay turns.
  return balls.every(b => b.potted || (Math.hypot(b.vx, b.vy) < EPS && Math.hypot(b.wx || 0, b.wy || 0) < EPS));
}
export function evolveCloth(b, dt) {
  b.wx ||= 0; b.wy ||= 0; b.wz ||= 0;
  const ux = b.vx - R * b.wy, uy = b.vy + R * b.wx, slip = Math.hypot(ux, uy);
  if (slip > EPS) {
    const t = Math.min(dt, 2 * slip / (7 * MU_S * G));
    const ax = -MU_S * G * ux / slip, ay = -MU_S * G * uy / slip;
    b.x += (b.vx * t + .5 * ax * t * t) * SCALE;
    b.y -= (b.vy * t + .5 * ay * t * t) * SCALE;
    b.vx += ax * t; b.vy += ay * t;
    b.wx += 2.5 / R * ay * t; b.wy -= 2.5 / R * ax * t;
    if (dt - t > EPS) roll(b, dt - t);
  } else roll(b, dt);
  b.wz = Math.sign(b.wz) * Math.max(0, Math.abs(b.wz) - SPIN_DECELERATION * dt);
}
function roll(b, dt) {
  const speed = Math.hypot(b.vx, b.vy);
  if (speed < EPS) { b.vx = b.vy = b.wx = b.wy = 0; return; }
  const t = Math.min(dt, speed / (MU_R * G)), f = Math.max(0, 1 - MU_R * G * t / speed);
  b.x += b.vx * t * (1 + f) / 2 * SCALE;
  b.y -= b.vy * t * (1 + f) / 2 * SCALE;
  b.vx *= f; b.vy *= f;
  b.wx = -b.vy / R; b.wy = b.vx / R;
}
function cross(a, b) { return [a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0]]; }
function dot(a, b) { return a[0] * b[0] + a[1] * b[1] + a[2] * b[2]; }
function contactVelocity(b, r) {
  const spin = cross([b.wx || 0, b.wy || 0, b.wz || 0], r);
  return [b.vx + spin[0], b.vy + spin[1], spin[2]];
}
function impulse(b, r, j) {
  b.vx += j[0] / M; b.vy += j[1] / M;
  const torque = cross(r, j);
  b.wx = (b.wx || 0) + torque[0] / I; b.wy = (b.wy || 0) + torque[1] / I; b.wz = (b.wz || 0) + torque[2] / I;
}
export function resolveBallCollision(a, b, nx, ny) {
  const approach = (a.vx - b.vx) * nx + (a.vy - b.vy) * ny;
  if (approach <= EPS) return 0;
  const ra = [R * nx, R * ny, 0], rb = [-R * nx, -R * ny, 0], t = [-ny, nx, 0];
  const jn = (1 + BALL_RESTITUTION) * approach * M / 2;
  impulse(a, ra, [-jn * nx, -jn * ny, 0]); impulse(b, rb, [jn * nx, jn * ny, 0]);
  const initialA = contactVelocity(a, ra), initialB = contactVelocity(b, rb);
  const initial = initialA.map((v, i) => v - initialB[i]);
  // Alciatore TP A.14 fit to Marlow's measurements, with speeds in m/s.
  const mu = .009951 + .108 * Math.exp(-1.088 * Math.hypot(dot(initial, t), initial[2]));
  for (let part = 0; part < 16; part++) {
    const va = contactVelocity(a, ra), vb = contactVelocity(b, rb);
    const u = va.map((v, i) => v - vb[i]), ut = dot(u, t), uz = u[2], slip = Math.hypot(ut, uz);
    if (slip < EPS) break;
    const et = ut / slip, ez = uz / slip, k = (7 * et * et + 5 * ez * ez) / M;
    const jt = Math.min(mu * jn / 16, slip / k);
    const j = [-jt * et * t[0], -jt * et * t[1], -jt * ez];
    impulse(a, ra, j); impulse(b, rb, j.map(v => -v));
  }
  return approach;
}
export function resolveCushion(b, nx, ny, restitution = WALL_RESTITUTION, mu = CUSHION_FRICTION) {
  // Raised rubber nose; slate constrains vertical translation. Energetic restitution
  // returns e² of normal compression work, while Coulomb friction dissipates energy.
  const h = CUSHION_NOSE_HEIGHT - 1, c = Math.sqrt(1 - h * h);
  const normal = [c * nx, c * ny, -h], r = normal.map(v => -R * v);
  const vn = () => c * (b.vx * nx + b.vy * ny), k = c * c / M;
  const incoming = vn();
  if (incoming >= -EPS) return 0;
  let compressed = 0;
  const increment = -incoming / k / 64;
  function normalImpulse(j) { impulse(b, r, normal.map(v => j * v)); }
  function friction(jn) {
    const u = contactVelocity(b, r), un = dot(u, normal), tangent = u.map((v, i) => v - un * normal[i]);
    const speed = Math.hypot(...tangent);
    if (speed < EPS) return;
    const d = tangent.map(v => v / speed), torque = cross(r, d);
    const effective = (d[0] * d[0] + d[1] * d[1]) / M + dot(torque, torque) / I;
    const jt = Math.min(mu * jn, speed / effective);
    impulse(b, r, d.map(v => -jt * v));
  }
  for (let i = 0; i < 256 && vn() < -1e-8; i++) {
    const before = vn(), j = Math.min(increment, -before / k);
    compressed -= before * j + .5 * k * j * j;
    normalImpulse(j); friction(j);
  }
  let available = Math.max(0, restitution * restitution * compressed);
  for (let i = 0; i < 256 && available > 1e-12; i++) {
    const before = vn();
    const allowed = (-before + Math.sqrt(before * before + 2 * k * available)) / k;
    const j = Math.min(increment, allowed);
    const work = before * j + .5 * k * j * j;
    normalImpulse(j); friction(j); available -= work;
  }
  return -incoming / c;
}
function collideRails(b, hits) {
  for (const s of CUSHION_SEGMENTS) {
    const p = closestOnSegment(b.x, b.y, s), dx = b.x - p.x, dy = b.y - p.y;
    const distance = Math.hypot(dx, dy);
    if (distance >= BALL_R || distance < EPS) continue;
    // Finite faces with rounded jaw tips. No wall crosses a pocket opening.
    let nx = dx / distance, ny = dy / distance;
    if (p.t > 0 && p.t < 1 && nx * s.nx + ny * s.ny < 0) { nx = s.nx; ny = s.ny; }
    const penetration = BALL_R - distance + 1e-5;
    b.x += nx * penetration; b.y += ny * penetration;
    const speed = resolveCushion(b, nx, -ny);
    if (speed > EPS) hits.push({ type: 'rail', speed: speed * SCALE / 60, number: b.number, jaw: s.jaw });
  }
}
export function step(balls, dt = 1 / 60) {
  if (!Number.isFinite(dt) || dt <= 0 || dt > .1) throw new RangeError('Physics step must be 0 < dt <= 0.1 seconds');
  const hits = [], potted = [];
  const maxSpeed = balls.reduce((s, b) => b.potted ? s : Math.max(s, Math.hypot(b.vx, b.vy), R * Math.hypot(b.wx || 0, b.wy || 0)), 0);
  const sub = Math.max(1, Math.ceil(maxSpeed * SCALE * dt / (BALL_R * .22))), h = dt / sub;
  for (let n = 0; n < sub; n++) {
    const active = balls.filter(b => !b.potted);
    for (const b of active) {
      evolveCloth(b, h);
      if (pocketAt(b.x, b.y)) { b.potted = true; clearMotion(b); potted.push(b); }
      else collideRails(b, hits);
    }
    for (let i = 0; i < active.length; i++) for (let j = i + 1; j < active.length; j++) {
      const a = active[i], b = active[j];
      if (a.potted || b.potted) continue;
      const dx = b.x - a.x, dy = b.y - a.y, distance = Math.hypot(dx, dy);
      if (distance >= BALL_R * 2 || distance < EPS) continue;
      const nx = dx / distance, ny = dy / distance, overlap = (BALL_R * 2 - distance + 1e-5) / 2;
      a.x -= nx * overlap; a.y -= ny * overlap; b.x += nx * overlap; b.y += ny * overlap;
      const speed = resolveBallCollision(a, b, nx, -ny);
      if (speed > EPS) hits.push({ type: 'ball', speed: speed * SCALE / 60, a: a.number, b: b.number });
    }
  }
  return { potted, hits };
}
export function placeCueExact(cue, balls, x, y) {
  if (!validPlacement(x, y, balls, cue)) return false;
  Object.assign(cue, { x, y }); clearMotion(cue); cue.potted = false; return true;
}
export function placeCue(cue, balls, x, y) {
  const minX = CUSHION + BALL_R, maxX = CUSHION + TABLE_W - BALL_R;
  const minY = CUSHION + BALL_R, maxY = CUSHION + TABLE_H - BALL_R;
  const cx = Math.min(maxX, Math.max(minX, x)), cy = Math.min(maxY, Math.max(minY, y));
  let found = null;
  // Find the nearest safe spot rather than pushing one overlap into another ball.
  for (let radius = 0; radius < Math.max(TABLE_W, TABLE_H) && !found; radius += BALL_R / 2) {
    const samples = radius === 0 ? 1 : Math.ceil(2 * Math.PI * radius / (BALL_R / 2));
    for (let i = 0; i < samples; i++) {
      const px = cx + radius * Math.cos(i * 2 * Math.PI / samples), py = cy + radius * Math.sin(i * 2 * Math.PI / samples);
      if (validPlacement(px, py, balls, cue)) { found = { x: px, y: py }; break; }
    }
  }
  if (!found) return false;
  Object.assign(cue, found); clearMotion(cue); cue.potted = false; return true;
}
